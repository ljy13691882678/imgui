inline constexpr size_t kItemDatabaseCount = sizeof(kItemDatabase) / sizeof(kItemDatabase[0]);

// 通过 objectID 二分查找物品信息；找不到返回 nullptr (kItemDatabase 已按 Id 升序排列)
inline const ItemDbEntry *FindItemById(uint64_t id)
{
    size_t lo = 0, hi = kItemDatabaseCount;
    while (lo < hi)
    {
        const size_t mid = lo + (hi - lo) / 2;
        if (kItemDatabase[mid].Id < id)
            lo = mid + 1;
        else
            hi = mid;
    }
    if (lo < kItemDatabaseCount && kItemDatabase[lo].Id == id)
        return &kItemDatabase[lo];
    return nullptr;
}

// 便捷封装：直接取中文名，找不到时返回 defaultName
inline const char *GetItemName(uint64_t id, const char *defaultName = "未知物品")
{
    const ItemDbEntry *entry = FindItemById(id);
    return entry ? entry->Name : defaultName;
}
